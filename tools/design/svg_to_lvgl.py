"""Turns a hand drawing from docs/design into an LVGL 9 image in C.

Input is either an RGBA PNG cutout (white glove, black outline and finger
lines, transparent elsewhere), resized to the target width, or a
single-colour SVG silhouette made of absolute M/L/C/Z subpaths with
fill-rule evenodd, drawn supersampled. The PNG keeps the finger lines; the
traced SVGs lose them. Output is an ARGB8888 lv_image_dsc_t cropped to the
shape.

Requires Pillow and NumPy:
    python tools/design/svg_to_lvgl.py <in.png|in.svg> <out.c> <symbol> <width_px>
"""
import re
import sys

import numpy as np
from PIL import Image, ImageChops, ImageDraw

SUPERSAMPLE = 8
CURVE_STEPS = 24


def subpaths(svg_text):
    """Yields each subpath as a list of (x, y) points in viewBox units."""
    for d in re.findall(r'<path[^>]*\sd="([^"]+)"', svg_text):
        tokens = re.findall(r"[MLCZmlcz]|-?\d*\.?\d+(?:e-?\d+)?", d)
        points, current, cmd, i = [], (0.0, 0.0), None, 0
        while i < len(tokens):
            tok = tokens[i]
            if tok.isalpha():
                if tok.islower():
                    raise ValueError(f"relative command {tok} not supported")
                cmd = tok
                i += 1
                if cmd == "Z":
                    if points:
                        yield points
                    points = []
                continue
            if cmd == "M":
                if points:
                    yield points
                current = (float(tokens[i]), float(tokens[i + 1]))
                points = [current]
                i += 2
                cmd = "L"  # implicit lineto after a moveto
            elif cmd == "L":
                current = (float(tokens[i]), float(tokens[i + 1]))
                points.append(current)
                i += 2
            elif cmd == "C":
                c1 = (float(tokens[i]), float(tokens[i + 1]))
                c2 = (float(tokens[i + 2]), float(tokens[i + 3]))
                end = (float(tokens[i + 4]), float(tokens[i + 5]))
                p0 = current
                for s in range(1, CURVE_STEPS + 1):
                    t = s / CURVE_STEPS
                    u = 1.0 - t
                    points.append((
                        u * u * u * p0[0] + 3 * u * u * t * c1[0] + 3 * u * t * t * c2[0] + t * t * t * end[0],
                        u * u * u * p0[1] + 3 * u * u * t * c1[1] + 3 * u * t * t * c2[1] + t * t * t * end[1],
                    ))
                current = end
                i += 6
            else:
                raise ValueError(f"unexpected token {tok}")
        if points:
            yield points


def from_png(src, width_px):
    img = Image.open(src).convert("RGBA")
    img = img.crop(img.getbbox())
    h = round(img.height * width_px / img.width)
    img = img.resize((width_px, h), Image.Resampling.LANCZOS)
    rgba = np.asarray(img, dtype=np.uint8)
    pixels = np.zeros_like(rgba)
    pixels[..., 0] = rgba[..., 2]  # LVGL ARGB8888 is B, G, R, A in memory
    pixels[..., 1] = rgba[..., 1]
    pixels[..., 2] = rgba[..., 0]
    pixels[..., 3] = rgba[..., 3]
    return pixels


def from_svg(src, width_px):
    text = open(src, encoding="utf-8").read()
    view = [float(v) for v in re.search(r'viewBox="([^"]+)"', text).group(1).split()]
    paths = list(subpaths(text))

    # Scale so the shape (not the viewBox) is width_px wide.
    xs = [p[0] for path in paths for p in path]
    scale = width_px / (max(xs) - min(xs))
    size = (int(view[2] * scale * SUPERSAMPLE) + 1, int(view[3] * scale * SUPERSAMPLE) + 1)
    mask = Image.new("1", size, 0)
    for path in paths:
        layer = Image.new("1", size, 0)
        ImageDraw.Draw(layer).polygon(
            [((x - view[0]) * scale * SUPERSAMPLE, (y - view[1]) * scale * SUPERSAMPLE)
             for x, y in path], fill=1)
        mask = ImageChops.logical_xor(mask, layer)  # even-odd

    alpha = mask.convert("L").resize(
        (size[0] // SUPERSAMPLE, size[1] // SUPERSAMPLE), Image.Resampling.BOX)
    box = alpha.getbbox()
    alpha = alpha.crop(box)
    w, h = alpha.size
    a = np.asarray(alpha, dtype=np.uint8)

    pixels = np.zeros((h, w, 4), np.uint8)
    pixels[..., 0:3] = 255  # B, G, R: white
    pixels[..., 3] = a
    return pixels


def main():
    src, out, symbol, width_px = sys.argv[1], sys.argv[2], sys.argv[3], int(sys.argv[4])
    pixels = from_png(src, width_px) if src.lower().endswith(".png") else from_svg(src, width_px)
    h, w = pixels.shape[:2]
    data = pixels.tobytes()

    lines = []
    for row in range(h):
        chunk = data[row * w * 4:(row + 1) * w * 4]
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in chunk) + ",")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(f"// Generated by tools/design/svg_to_lvgl.py from {src.replace(chr(92), '/')}.\n")
        f.write("// Do not edit: change the SVG and regenerate.\n")
        f.write('#include "lvgl.h"\n\n')
        f.write(f"static const uint8_t {symbol}_map[] = {{\n")
        f.write("\n".join(lines))
        f.write("\n};\n\n")
        f.write(f"const lv_image_dsc_t {symbol} = {{\n")
        f.write("    .header = {\n")
        f.write("        .magic = LV_IMAGE_HEADER_MAGIC,\n")
        f.write("        .cf = LV_COLOR_FORMAT_ARGB8888,\n")
        f.write("        .flags = 0,\n")
        f.write(f"        .w = {w},\n")
        f.write(f"        .h = {h},\n")
        f.write(f"        .stride = {w * 4},\n")
        f.write("    },\n")
        f.write(f"    .data_size = sizeof({symbol}_map),\n")
        f.write(f"    .data = {symbol}_map,\n")
        f.write("};\n")
    print(f"{symbol}: {w}x{h} px")


if __name__ == "__main__":
    main()
